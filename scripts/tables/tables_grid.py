"""LaTeX tables for the training grids, from data/<system>_train_summary.json
(written by scripts/aggregate_runs.py).

For each system:
  tables/grid_<system>.tex        full table, sorted by final gradient norm:
                                  schedule, class, realized Lambda_max, final grad norm,
                                  valid time (thr 0.3 and 0.5), stability horizon, |lambda_1 err|
  tables/matched_<system>.tex     matched-budget pairs: for each beta, the saturating rule
                                  (capped and uncapped where both exist) vs the constant
                                  window at the same budget

    python scripts/tables/tables_grid.py --data_dir data --out_dir tables
"""
import argparse
import json
import math
import re
from pathlib import Path

CLASS_LABEL = {
    "single_shoot": "constant window",
    "const_window_matched_budget": "constant window, matched budget",
    "adaptive": "saturating",
    "global_lyapunov": "ramp",
    "mp_node": "multi-window (MP-NODE)",
}
SYSTEM_LABEL = {"l63": "Lorenz-63", "l96_n40": "Lorenz-96 ($N{=}40$)", "ks_l22": "Kuramoto--Sivashinsky"}


def pm(m, s, d=2):
    if m is None or (isinstance(m, float) and math.isnan(m)):
        return "--"
    if s is None or (isinstance(s, float) and (math.isnan(s) or s == 0)):
        return f"${m:.{d}f}$"
    return f"${m:.{d}f} \\pm {s:.{d}f}$"


def sci(x):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    e = int(math.floor(math.log10(abs(x)))) if x != 0 else 0
    return f"${x / 10 ** e:.1f}{{\\rm e}}{{{e:+d}}}$"


def label(r):
    n = r["config"]
    cls = r["schedule"]
    if cls == "ss":
        return f"$W{{=}}{r['W_nominal']:g}\\,T_\\lambda$"
    if cls in ("const_g", "sat"):
        cap_match = re.search(r"_Wmax([0-9.]+)", n)
        cap = r", $W_{\max}{=}" + (cap_match.group(1) if cap_match else "2") + r"T_\lambda$"
        norm = ", unweighted" if "per_segment" in n else (", inverse-window weighted" if cls == "sat" else "")
        base = r"W_g^{\max}" if cls == "const_g" else r"W^\star"
        return f"${base}(\\beta{{=}}{r['beta']:g})${cap}{norm}"
    if cls == "ramp":
        return "ramp $0.1 \\to 1\\,T_\\lambda$"
    if cls == "mpnode":
        return f"$K{{=}}{r['K']}$, $W{{=}}{r['W_nominal']:g}\\,T_\\lambda$"
    return n


def full_table(recs, system, out):
    recs = sorted(recs, key=lambda r: r["final_grad_norm_mean"] if r["final_grad_norm_mean"] == r["final_grad_norm_mean"] else 1e99)
    L = [f"% Generated by scripts/tables/tables_grid.py from data/{system}_train_summary.json",
         "\\begin{tabular}{llcccccc}", "\\toprule",
         "Schedule & Class & $\\Lambda_{\\max}$ & $\\|\\nabla L\\|$ & $t_{\\rm valid}/T_\\lambda$ (0.3) & "
         "$t_{\\rm valid}/T_\\lambda$ (0.5) & stable $T/T_\\lambda$ & $|\\hat\\lambda_1-\\lambda_1|$ \\\\", "\\midrule"]
    for r in recs:
        L.append(f"{label(r)} & {CLASS_LABEL.get(r['class'], r['class'])} & ${r['Lambda_max_mean']:.2f}$ & "
                 f"{sci(r['final_grad_norm_mean'])} & {pm(r['valid_time_mean'], r['valid_time_std'])} & "
                 f"{pm(r['valid_time_thr05_mean'], r['valid_time_thr05_std'])} & "
                 f"{pm(r.get('blowup_time_mean'), r.get('blowup_time_std'), 0)} & "
                 f"{pm(r.get('lambda1_error_mean'), r.get('lambda1_error_std'), 3)} \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(L) + "\n")


def matched_table(recs, system, out):
    by = {r["config"]: r for r in recs}
    betas = sorted({r["beta"] for r in recs if r["schedule"] in ("sat", "const_g") and r["beta"] is not None})
    L = [f"% Generated by scripts/tables/tables_grid.py from data/{system}_train_summary.json",
         "\\begin{tabular}{lcccc}", "\\toprule",
         "$\\beta$ & schedule & $\\Lambda_{\\max}$ & $\\|\\nabla L\\|$ & $t_{\\rm valid}/T_\\lambda$ \\\\", "\\midrule"]
    for b in betas:
        rows = sorted([r for r in recs if r.get("beta") == b and r["schedule"] in ("sat", "const_g")],
                      key=lambda r: (float(re.search(r"_Wmax([0-9.]+)", r["config"]).group(1))
                                     if "_Wmax" in r["config"] else 2.0,
                                     r["schedule"] != "const_g", r["config"]))
        first = True
        for r in rows:
            name = label(r)
            L.append(f"{f'${b:g}$' if first else ''} & {name} & ${r['Lambda_max_mean']:.2f}$ & "
                     f"{sci(r['final_grad_norm_mean'])} & {pm(r['valid_time_mean'], r['valid_time_std'])} \\\\")
            first = False
        L.append("\\midrule")
    L[-1] = "\\bottomrule"
    L.append("\\end{tabular}")
    out.write_text("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data_dir", type=Path, default=Path("data"))
    ap.add_argument("--out_dir", type=Path, default=Path("tables"))
    a = ap.parse_args()
    a.out_dir.mkdir(parents=True, exist_ok=True)
    for f in sorted(a.data_dir.glob("*_train_summary.json")):
        system = f.name.replace("_train_summary.json", "")
        recs = json.load(open(f))
        full_table(recs, system, a.out_dir / f"grid_{system}.tex")
        matched_table(recs, system, a.out_dir / f"matched_{system}.tex")
        print(f"[tables_grid] {system}: {len(recs)} configs -> grid_{system}.tex, matched_{system}.tex")


if __name__ == "__main__":
    main()
