"""Generate the LaTeX body for Table 1 (tab:hetero) from theorem-verification JSON.

Reads CV at tau_factor in {0.5, 1.0, 2.0} for each system, plus the
reference lambda_1 from `sys.reference_lambda1`.

EXPECTED INPUT
--------------
results/corollary3/results_task{0..3}.json from test_corollary3.py
runs at three tau_factors per system.

USAGE
-----
    python scripts/tables/table1_hetero.py \\
        --corollary3_dir results/corollary3 \\
        --out tables/table1_hetero.tex

OUTPUT
------
A LaTeX `tabular` body (no \begin{table}/\end{table} wrapping) that
you can \input{} into the paper, replacing the hand-written contents
of tab:hetero.
"""
import argparse
import json
from pathlib import Path
import sys

# Make the systems package importable for lambda_1 / T_lambda lookups
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
from src.systems import get_system

DISPLAY = {
    "l63": "Lorenz-63",
    "rossler": "R\\\"ossler",
    "l96_n40": "Lorenz-96 ($N{=}40$)",
    "ks_l22": "Kuramoto--Sivashinsky ($N{=}64$, $L{=}22$)",
}
ORDER = ["l63", "rossler", "l96_n40", "ks_l22"]


def load(d: Path):
    """Return {system: {tau_factor: cv}}."""
    out = {}
    for p in sorted(d.glob("results_task*.json")):
        if "__1_" in p.name:
            continue
        with open(p) as f:
            for r in json.load(f):
                out.setdefault(r["system"], {})[r["tau_factor"]] = r["cv"]
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--corollary3_dir", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    cv = load(args.corollary3_dir)

    lines = [
        "% Generated by scripts/tables/table1_hetero.py",
        "% Source: results/corollary3/results_task*.json (test_corollary3.py)",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "System & $\\lambda_1$ & $T_\\lambda$ & $\\CV$ at $\\tau{=}T_\\lambda/2$ "
        "& $\\CV$ at $\\tau{=}T_\\lambda$ & $\\CV$ at $\\tau{=}2T_\\lambda$\\\\",
        "\\midrule",
    ]
    for sys_name in ORDER:
        if sys_name not in cv:
            continue
        sys_obj = get_system(sys_name)
        lam = sys_obj.reference_lambda1
        Tl = 1.0 / lam
        cv_half = cv[sys_name].get(0.5, float("nan"))
        cv_one = cv[sys_name].get(1.0, float("nan"))
        cv_two = cv[sys_name].get(2.0, float("nan"))
        emph = ("\\mathbf{", "}") if sys_name == "l63" else ("", "")
        lines.append(
            f"{DISPLAY[sys_name]} & ${lam:.3f}$ & ${Tl:.3f}$ "
            f"& ${emph[0]}{cv_half:.3f}{emph[1]}$ "
            f"& ${cv_one:.3f}$ & ${cv_two:.3f}$ \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"[table1_hetero] wrote {args.out}")


if __name__ == "__main__":
    main()
