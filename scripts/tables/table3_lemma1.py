"""Generate the LaTeX body for Table 3 (tab:lemma1): Lambda(W) mean ± std
across 20 trajectories per system at six W values.

USAGE
-----
    python scripts/tables/table3_lemma1.py \\
        --lemma1_dir results/lemma1 \\
        --corollary3_dir results/corollary3 \\
        --out tables/table3_lemma1.tex
"""
import argparse
import json
from pathlib import Path

import numpy as np

DISPLAY = {
    "l63": "L63", "rossler": "R\\\"ossler",
    "l96_n40": "L96 ($N{=}40$)", "ks_l22": "KS ($L{=}22$)",
}
ORDER = ["l63", "rossler", "l96_n40", "ks_l22"]


def load_tangent(d: Path):
    out = {}
    for p in sorted(d.glob("tangent_task*.json")):
        with open(p) as f:
            for r in json.load(f):
                out.setdefault(r["system"], []).append(r)
    return out


def load_cv(d: Path):
    cv = {}
    for p in sorted(d.glob("results_task*.json")):
        if "__1_" in p.name:
            continue
        with open(p) as f:
            for r in json.load(f):
                if abs(r["tau_factor"] - 0.5) < 1e-6:
                    cv[r["system"]] = r["cv"]
    return cv


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lemma1_dir", required=True, type=Path)
    ap.add_argument("--corollary3_dir", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    tangent = load_tangent(args.lemma1_dir)
    cv = load_cv(args.corollary3_dir)
    W_factors = sorted(set(r["W_factor"] for s in tangent.values() for r in s))

    header_cols = " & ".join(f"${wf}$" for wf in W_factors)
    lines = [
        "% Generated by scripts/tables/table3_lemma1.py",
        "% Source: results/lemma1/tangent_task*.json (test_lemma1.py --mode tangent)",
        "\\begin{tabular}{l" + "c" * (len(W_factors) + 1) + "}",
        "\\toprule",
        f"System ($\\CV$) & $W/T_\\lambda{{=}}{W_factors[0]}$ & "
        + " & ".join(f"${wf}$" for wf in W_factors[1:]) + " \\\\",
        "\\midrule",
    ]
    for sys_name in ORDER:
        if sys_name not in tangent:
            continue
        cells = [f"{DISPLAY[sys_name]} (${cv.get(sys_name, 0):.2f}$)"]
        for wf in W_factors:
            ls = np.array([r["Lambda_W"] for r in tangent[sys_name]
                           if abs(r["W_factor"] - wf) < 1e-9])
            cells.append(f"${ls.mean():.2f} \\pm {ls.std():.2f}$")
        lines.append(" & ".join(cells) + " \\\\")

    lines.append("\\midrule")
    pred_cells = ["\\emph{Predicted} $\\lambda_1 W$"]
    for wf in W_factors:
        pred_cells.append(f"${wf:.2f}$")
    lines.append(" & ".join(pred_cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"[table3_lemma1] wrote {args.out}")


if __name__ == "__main__":
    main()
