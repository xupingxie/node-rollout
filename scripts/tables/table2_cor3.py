"""Generate the LaTeX body for Table 2 (tab:cor3): Corollary 3 verification.

Reads cv, cv_eff, W_g_max, W_bar_star, ratio_minus_one, cv_sq_bound
from the test_corollary3.py output.

USAGE
-----
    python scripts/tables/table2_cor3.py \\
        --corollary3_dir results/corollary3 \\
        --out tables/table2_cor3.tex
"""
import argparse
import json
from pathlib import Path

DISPLAY = {
    "l63": "L63", "rossler": "R\\\"ossler",
    "l96_n40": "L96 ($N{=}40$)", "ks_l22": "KS ($L{=}22$)",
}
ORDER = ["l63", "rossler", "l96_n40", "ks_l22"]


def load(d: Path):
    out = {}
    for p in sorted(d.glob("results_task*.json")):
        if "__1_" in p.name:
            continue
        with open(p) as f:
            for r in json.load(f):
                out.setdefault(r["system"], []).append(r)
    for k in out:
        out[k].sort(key=lambda r: r["tau_factor"])
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--corollary3_dir", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    data = load(args.corollary3_dir)

    lines = [
        "% Generated by scripts/tables/table2_cor3.py",
        "% Source: results/corollary3/results_task*.json (test_corollary3.py)",
        "\\begin{tabular}{llcccccc}",
        "\\toprule",
        "System & $\\tau/T_\\lambda$ & $\\CV$ & $\\CV_{\\rm eff}$ & $W_g^{\\max}$ & $\\bar W^\\star$ &"
        " realized gap & bound $\\CV_{\\rm eff}^2$ \\\\",
        "\\midrule",
    ]
    first = True
    for sys_name in ORDER:
        if sys_name not in data:
            continue
        if not first:
            lines.append("\\midrule")
        first = False
        for i, r in enumerate(data[sys_name]):
            system_col = DISPLAY[sys_name] if i == 0 else ""
            gap_str = (f"$\\mathbf{{{r['ratio_minus_one']:.2f}}}$"
                       if (sys_name == "l63" and r["tau_factor"] == 0.5)
                       else f"${r['ratio_minus_one']:.2f}$")
            lines.append(
                f"{system_col} & {r['tau_factor']:.1f} & "
                f"${r['cv']:.3f}$ & ${r['cv_eff']:.3f}$ & ${r['W_g_max']:.3f}$ & "
                f"${r['W_bar_star']:.3f}$ & {gap_str} & "
                f"${r['cv_sq_bound']:.3f}$ \\\\"
            )
    lines += ["\\bottomrule", "\\end{tabular}"]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"[table2_cor3] wrote {args.out}")


if __name__ == "__main__":
    main()
