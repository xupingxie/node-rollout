"""Generate the LaTeX body for Table 4 (tab:prop4): Proposition 4 verification.

USAGE
-----
    python scripts/tables/table4_prop4.py \\
        --proposition4_dir results/proposition4 \\
        --out tables/table4_prop4.tex
"""
import argparse
import json
from pathlib import Path

DISPLAY = {
    "l63": "L63", "rossler": "R\\\"ossler",
    "l96_n40": "L96 ($N{=}40$)", "ks_l22": "KS ($L{=}22$)",
}
ORDER = ["l63", "rossler", "l96_n40", "ks_l22"]


def load(d: Path):
    out = {}
    for p in sorted(d.glob("*.json")):
        if "gaussian" in p.name:          # stress test, reported separately
            continue
        with open(p) as f:
            for r in json.load(f):
                if r.get("noise_model") != "uniform":
                    continue
                out.setdefault(r["system"], []).append(r)
    for k in out:
        out[k].sort(key=lambda r: r["sigma_eps"])
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--proposition4_dir", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    data = load(args.proposition4_dir)

    lines = [
        "% Generated by scripts/tables/table4_prop4.py",
        "% Source: results/proposition4/*.json (test_proposition4.py)",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "System & $\\beta$ & $\\epsilon$ & "
        "feasibility min & bound ratio \\\\",
        "\\midrule",
    ]
    first = True
    for sys_name in ORDER:
        if sys_name not in data:
            continue
        if not first:
            lines.append("\\midrule")
        first = False
        for i, r in enumerate(data[sys_name]):
            system_col = DISPLAY[sys_name] if i == 0 else ""
            beta_col = f"${r['beta']:.3f}$" if i == 0 else ""
            feas_pct = r["feasibility_fraction_min"] * 100
            ratio = (r["coverage_loss_max"] / r["theoretical_bound"]) * 100
            lines.append(
                f"{system_col} & {beta_col} & "
                f"${r['epsilon']:.2f}$ & "
                f"${feas_pct:.2f}\\%$ & ${ratio:.0f}\\%$ \\\\"
            )
    lines += ["\\bottomrule", "\\end{tabular}"]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"[table4_prop4] wrote {args.out}")


if __name__ == "__main__":
    main()
