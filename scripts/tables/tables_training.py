"""Generate LaTeX bodies for the training-summary tables:
  Table 5 (tab:l63_headline)        from data/l63_ablation_summary.json (6 baseline rows)
  Table 6 (tab:l63_longtime)        from data/longtime_stats_summary.json
  Table 7 (tab:ks_pilot)            from data/ks_pilot_summary.json
  Table 9 (tab:l63_ablation_full)   from data/l63_ablation_summary.json (all 14 rows)
  Table 8 (tab:l96_results)         from data/l96_results_summary.json

Each uses a slightly different LaTeX column layout. The script handles
all five with a small per-table formatter.

USAGE
-----
    python scripts/tables/tables_training.py \\
        --data_dir data \\
        --out_dir tables
"""
import argparse
import json
from pathlib import Path


# ----------------------------- helpers ----------------------------------
def fmt(mean, std, digits=3):
    if std == 0.0 or std is None:
        return f"${mean:.{digits}f}$"
    return f"${mean:.{digits}f} \\pm {std:.{digits}f}$"


def fmt_sci(mean, std):
    """Scientific notation, e.g. 1.38e-4 ± 1.0e-4."""
    if mean == 0:
        return "$0$"
    exp_m = int(f"{mean:.0e}".split("e")[1])
    mant_m = mean / (10 ** exp_m)
    exp_s = int(f"{std:.0e}".split("e")[1]) if std > 0 else exp_m
    mant_s = std / (10 ** exp_s) if std > 0 else 0
    base = f"{mant_m:.2f}{{\\rm e{{{exp_m:+d}}}}}"
    if std > 0:
        return f"${base} \\pm {mant_s:.1f}{{\\rm e{{{exp_s:+d}}}}}$"
    return f"${base}$"


# ----------------------------- Table 5 -----------------------------------
def table5_l63_headline(records, out: Path) -> None:
    """Six headline L63 baselines (subset of the ablation summary)."""
    # Choose the 6 records that appear in tab:l63_headline in the paper.
    wanted = [
        ("Single-shoot ($W{=}0.30$)", "single-window",  "single_shoot_W=0.30"),
        ("MP-NODE ($3 \\times 0.30$)", "multi-window",  "MP-NODE (3x0.30)"),
        ("Single-shoot ($W{=}0.60$)", "single-window",  "single_shoot_W=0.60"),
        ("Adaptive (\\texttt{q4/inv\\_W}, ours)", "single-rollout", "q4/inv_W"),
        ("Global Lyapunov curriculum", "single-rollout", "global_lyapunov_baseline"),
        ("Single-shoot ($W{=}1.00$)", "single-window",  "single_shoot_W=1.00"),
    ]
    by_config = {r["config"]: r for r in records}
    lines = [
        "% Generated by scripts/tables/tables_training.py (Table 5)",
        "% Source: data/l63_ablation_summary.json",
        "\\begin{tabular}{llcc}",
        "\\toprule",
        "Method & Class & $t_{\\mathrm{valid}}/T_\\lambda$ $\\uparrow$ & "
        "Final loss $\\downarrow$ \\\\",
        "\\midrule",
    ]
    for label, cls, key in wanted:
        if key not in by_config:
            continue
        r = by_config[key]
        vt = fmt(r["valid_time_mean"], r["valid_time_std"], 3)
        # Final loss values are in the ablation table; if absent, write a dash.
        fl_mean = r.get("final_loss_mean")
        fl_std = r.get("final_loss_std")
        if fl_mean is not None:
            fl = fmt(fl_mean, fl_std, 2)
        else:
            fl = "---"
        bold = "\\textbf{" if "Adaptive" in label else ""
        end_bold = "}" if bold else ""
        lines.append(f"{bold}{label}{end_bold} & {bold}{cls}{end_bold} & "
                     f"{bold}{vt}{end_bold} & {bold}{fl}{end_bold} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    print(f"[table5_l63_headline] wrote {out}")


# ----------------------------- Table 6 -----------------------------------
def table6_l63_longtime(records, out: Path) -> None:
    """L63 long-time statistical fidelity."""
    name_map = {
        "baseline_single_W030":   "Single-shoot ($W{=}0.30$)",
        "baseline_single_W100":   "Single-shoot ($W{=}1.00$)",
        "baseline_mpnode":        "MP-NODE ($3{\\times}0.30$)",
        "baseline_global":        "Global Lyapunov",
        "adaptive_q4_invW":       "Adaptive (\\texttt{q4/inv\\_W}, ours)",
    }
    lines = [
        "% Generated by scripts/tables/tables_training.py (Table 6)",
        "% Source: data/longtime_stats_summary.json",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Method & Marginal MMD $\\downarrow$ & PSD $L^2$ $\\downarrow$ & "
        "$|\\hat\\lambda_1 - \\lambda_1^\\star|$ $\\downarrow$ \\\\",
        "\\midrule",
    ]
    # Find best in each column
    mmd_min = min(r["marginal_mmd_mean"] for r in records)
    psd_min = min(r["power_spectrum_l2_mean"] for r in records)
    lam_min = min(r["lambda1_error_mean"] for r in records)
    for key, label in name_map.items():
        rec = next((r for r in records if r["config_name"] == key), None)
        if rec is None:
            continue
        mmd_cell = fmt_sci(rec["marginal_mmd_mean"], rec["marginal_mmd_std"])
        psd_cell = fmt(rec["power_spectrum_l2_mean"], rec["power_spectrum_l2_std"], 3)
        lam_cell = fmt(rec["lambda1_error_mean"], rec["lambda1_error_std"], 3)
        if rec["marginal_mmd_mean"] == mmd_min:
            mmd_cell = mmd_cell.replace("$", "$\\mathbf{", 1)[::-1].replace("$", "}$", 1)[::-1]
        if rec["power_spectrum_l2_mean"] == psd_min:
            psd_cell = psd_cell.replace("$", "$\\mathbf{", 1)[::-1].replace("$", "}$", 1)[::-1]
        if rec["lambda1_error_mean"] == lam_min:
            lam_cell = lam_cell.replace("$", "$\\mathbf{", 1)[::-1].replace("$", "}$", 1)[::-1]
        lines.append(f"{label} & {mmd_cell} & {psd_cell} & {lam_cell} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    print(f"[table6_l63_longtime] wrote {out}")


# ----------------------------- Table 7 -----------------------------------
def table7_ks_pilot(records, out: Path) -> None:
    """KS pilot summary (7 methods)."""
    name_map = {
        "ks_baseline_mpnode_v2":         ("MP-NODE ($3 \\times W$)",       "multi-window"),
        "ks_baseline_single_W2_v2":      ("Single-shoot ($W{=}2$)",        "single-window"),
        "ks_baseline_single_W6_v2":      ("Single-shoot ($W{=}6$)",        "single-window"),
        "ks_adaptive_q4_invW_v2":        ("Adaptive \\texttt{q4/inv\\_W}, ours", "single-rollout"),
        "ks_adaptive_q4_persegment_v2":  ("Adaptive \\texttt{q4/persegment}",    "single-rollout"),
        "ks_baseline_global_v2":         ("Global Lyapunov",               "single-rollout"),
        "ks_adaptive_q4_global_v2":      ("Adaptive \\texttt{q4/global}",  "single-rollout"),
    }
    lines = [
        "% Generated by scripts/tables/tables_training.py (Table 7)",
        "% Source: data/ks_pilot_summary.json",
        "\\begin{tabular}{llccc}",
        "\\toprule",
        "Method & Class & $t_{\\mathrm{valid}}/T_\\lambda$ $\\uparrow$ & "
        "Final loss $\\downarrow$ & Final $\\|\\nabla L\\|$ \\\\",
        "\\midrule",
    ]
    # Multi-window block then mid-rule then single-rollout block (mirror paper)
    multi = ["ks_baseline_mpnode_v2", "ks_baseline_single_W2_v2", "ks_baseline_single_W6_v2"]
    single = ["ks_adaptive_q4_invW_v2", "ks_adaptive_q4_persegment_v2",
              "ks_baseline_global_v2", "ks_adaptive_q4_global_v2"]
    for group_idx, group in enumerate([multi, single]):
        if group_idx == 1:
            lines.append("\\midrule")
        for key in group:
            rec = next((r for r in records if r["config_name"] == key), None)
            if rec is None:
                continue
            label, cls = name_map[key]
            vt = fmt(rec["valid_time_over_Tlambda_mean"],
                     rec["valid_time_over_Tlambda_std"], 3)
            fl = f"${rec['final_loss_mean']:.1e}$".replace("e-0", "{\\rm e{-}}")
            gn = f"${rec['final_grad_norm_mean']:.2f}$"
            if "invW" in key or "MP-NODE" in label or "mpnode" in key:
                vt = vt.replace("$", "$\\mathbf{", 1)[::-1].replace("$", "}$", 1)[::-1] if "invW" in key else \
                     vt.replace("$", "$\\mathbf{", 1)[::-1].replace("$", "}$", 1)[::-1] if "mpnode" in key else vt
            lines.append(f"{label} & {cls} & {vt} & {fl} & {gn} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    print(f"[table7_ks_pilot] wrote {out}")


# ----------------------------- Table 8 -----------------------------------
def table8_l96(records, out: Path) -> None:
    """L96 N=40 training results."""
    lines = [
        "% Generated by scripts/tables/tables_training.py (Table 8)",
        "% Source: data/l96_results_summary.json",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Method & Final loss $\\downarrow$ & Final $\\|\\nabla L\\|$ & "
        "$t_{\\mathrm{valid}}/T_\\lambda$ \\\\",
        "\\midrule",
    ]
    for r in records:
        fl = fmt(r["final_loss_mean"], r["final_loss_std"], 2)
        gn = fmt(r["final_grad_norm_mean"], r["final_grad_norm_std"], 2)
        floor_mark = "^*" if r.get("valid_time_at_floor") else ""
        vt = (f"${r['valid_time_over_Tlambda_mean']:.3f} "
              f"\\pm {r['valid_time_over_Tlambda_std']:.3f}{floor_mark}$")
        lines.append(f"{r['config']} & {fl} & {gn} & {vt} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    print(f"[table8_l96] wrote {out}")


# ----------------------------- Table 9 -----------------------------------
def table9_l63_ablation_full(records, out: Path) -> None:
    """Full 14-config L63 ablation."""
    order = [
        ("Single-shoot ($W{=}0.30$)",        "single_shoot_W=0.30"),
        ("MP-NODE ($3 \\times 0.30$)",       "MP-NODE (3x0.30)"),
        ("Single-shoot ($W{=}0.60$)",        "single_shoot_W=0.60"),
        ("Global Lyapunov curriculum",       "global_lyapunov_baseline"),
        ("Single-shoot ($W{=}1.00$)",        "single_shoot_W=1.00"),
        ("\\texttt{q4/inv\\_W}",             "q4/inv_W"),
        ("\\texttt{q16/inv\\_W}",            "q16/inv_W"),
        ("\\texttt{exact/inv\\_W}",          "exact/inv_W"),
        ("\\texttt{q16/per\\_segment}",      "q16/per_segment"),
        ("\\texttt{q4/per\\_segment}",       "q4/per_segment"),
        ("\\texttt{exact/per\\_segment}",    "exact/per_segment"),
        ("\\texttt{q4/global}",              "q4/global"),
        ("\\texttt{exact/global}",           "exact/global"),
        ("\\texttt{q16/global}",             "q16/global"),
    ]
    by_config = {r["config"]: r for r in records}
    lines = [
        "% Generated by scripts/tables/tables_training.py (Table 9)",
        "% Source: data/l63_ablation_summary.json",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Configuration & Final loss & Final $\\|\\nabla L\\|$ & "
        "$t_{\\mathrm{valid}}/T_\\lambda$ & Wallclock (s) \\\\",
        "\\midrule",
    ]
    lines.append("\\emph{Baselines} \\\\")
    for i, (label, key) in enumerate(order):
        if i == 5:
            lines.append("\\midrule\n\\emph{Adaptive ablation grid (3 bucketing $\\times$ 3 loss\\_norm)} \\\\")
        r = by_config.get(key)
        if r is None:
            lines.append(f"{label} & --- & --- & --- & --- \\\\")
            continue
        fl_mean = r.get("final_loss_mean")
        fl = fmt(fl_mean, r.get("final_loss_std"), 2) if fl_mean else "---"
        gn_mean = r.get("final_grad_norm_mean")
        gn = (f"${gn_mean:.0f} \\pm {r.get('final_grad_norm_std', 0):.0f}$"
              if gn_mean else "---")
        bold = "\\textbf{" if key == "q4/inv_W" else ""
        end_bold = "}" if bold else ""
        vt = fmt(r["valid_time_mean"], r["valid_time_std"], 3)
        if key == "q4/inv_W":
            vt = f"$\\mathbf{{{r['valid_time_mean']:.3f} \\pm {r['valid_time_std']:.3f}}}$"
        wc = r.get("wallclock_seconds", "---")
        wc_str = f"${wc}$" if isinstance(wc, (int, float)) else wc
        lines.append(f"{bold}{label}{end_bold} & {fl} & {gn} & {vt} & {wc_str} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")
    print(f"[table9_l63_ablation_full] wrote {out}")


# ----------------------------- main --------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data_dir", required=True, type=Path)
    ap.add_argument("--out_dir", required=True, type=Path)
    args = ap.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    abl_path = args.data_dir / "l63_ablation_summary.json"
    if abl_path.exists():
        recs = json.loads(abl_path.read_text())
        table5_l63_headline(recs, args.out_dir / "table5_l63_headline.tex")
        table9_l63_ablation_full(recs, args.out_dir / "table9_l63_ablation_full.tex")
    else:
        print(f"  SKIP table 5 + 9: {abl_path} not found")

    lt_path = args.data_dir / "longtime_stats_summary.json"
    if lt_path.exists():
        recs = json.loads(lt_path.read_text())
        table6_l63_longtime(recs, args.out_dir / "table6_l63_longtime.tex")
    else:
        print(f"  SKIP table 6: {lt_path} not found")

    ks_path = args.data_dir / "ks_pilot_summary.json"
    if ks_path.exists():
        recs = json.loads(ks_path.read_text())
        table7_ks_pilot(recs, args.out_dir / "table7_ks_pilot.tex")
    else:
        print(f"  SKIP table 7: {ks_path} not found")

    l96_path = args.data_dir / "l96_results_summary.json"
    if l96_path.exists():
        recs = json.loads(l96_path.read_text())
        table8_l96(recs, args.out_dir / "table8_l96.tex")
    else:
        print(f"  SKIP table 8: {l96_path} not found")


if __name__ == "__main__":
    main()
